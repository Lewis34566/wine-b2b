  var hooks = [];
  var lang = (function () {
    try { return localStorage.getItem(LS_KEY) || 'zh'; } catch (e) { return 'zh'; }
  })();
  if (SUPPORTED.indexOf(lang) === -1) lang = 'zh';

  function lookup(dict, key) {
    return dict && Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : null;
  }

  function t(key, vars) {
    var s = lookup(I18N[lang], key);
    if (s == null) s = lookup(I18N.zh, key);
    if (s == null) s = String(key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split('{' + k + '}').join(String(vars[k] == null ? '' : vars[k]));
      });
    }
    return s;
  }

  function getLang() { return lang; }

  function setLang(v) {
    if (SUPPORTED.indexOf(v) === -1) return;
    lang = v;
    try { localStorage.setItem(LS_KEY, v); } catch (e) {}
    applyLang(v);
  }

  function onLangChange(fn) { hooks.push(fn); }

  function applyLang(v) {
    document.documentElement.lang = LOCALES[v];
    var page = document.documentElement.getAttribute('data-page');
    if (page) {
      document.title = t('title_' + page);
      var m = document.getElementById('metaDesc');
      if (m) m.setAttribute('content', t('desc_' + page));
    }
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    document.querySelectorAll('[data-lang-switch]').forEach(function (el) { el.value = v; });
    if (WineApp && WineApp.initNav) WineApp.initNav();
    hooks.forEach(function (fn) {
      try { fn(v); } catch (e) { if (window.console) console.error('[i18n hook]', e); }
    });
  }

